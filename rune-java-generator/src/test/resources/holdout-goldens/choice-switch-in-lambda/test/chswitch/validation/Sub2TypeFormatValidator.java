package test.chswitch.validation;

import com.google.common.collect.Lists;
import com.rosetta.model.lib.expression.ComparisonResult;
import com.rosetta.model.lib.path.RosettaPath;
import com.rosetta.model.lib.validation.ValidationResult;
import com.rosetta.model.lib.validation.Validator;
import java.util.List;
import test.chswitch.Sub2;

import static com.google.common.base.Strings.isNullOrEmpty;
import static com.rosetta.model.lib.validation.ValidationResult.failure;
import static com.rosetta.model.lib.validation.ValidationResult.success;
import static java.util.stream.Collectors.toList;

public class Sub2TypeFormatValidator implements Validator<Sub2> {

	private List<ComparisonResult> getComparisonResults(Sub2 o) {
		return Lists.<ComparisonResult>newArrayList(
			);
	}

	@Override
	public List<ValidationResult<?>> getValidationResults(RosettaPath path, Sub2 o) {
		return getComparisonResults(o)
			.stream()
			.map(res -> {
				if (!isNullOrEmpty(res.getError())) {
					return failure("Sub2", ValidationResult.ValidationType.TYPE_FORMAT, "Sub2", path, "", res.getError());
				}
				return success("Sub2", ValidationResult.ValidationType.TYPE_FORMAT, "Sub2", path, "");
			})
			.collect(toList());
	}

}
