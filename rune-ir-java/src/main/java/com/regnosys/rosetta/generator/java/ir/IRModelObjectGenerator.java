    public java.util.Map<String, Integer> derivedTypeFormatChecksByElement() {
        return derivedReconciler.typeFormatChecksByElement();
    }

    /**
     * THE POJO SHADOW RENDERS of every {@code data} declaration this pass saw (v3.3 seat 9, PR #645 commit 4), keyed
     * by the POJO's OUTPUT KEY. Each value is a two- or three-element array the D11 host reads REFLECTIVELY, in the
     * shape the other seams take, so the host stays decoupled from {@code rune-ir-java}'s types:
     * <ul>
     *   <li>{@code {"RENDERED", <the file text>, <SECTION:line,... >}} - the emitter wrote the whole file; the third
     *       element gives the 1-based line at which each section starts, so the host can name the SECTION a first
     *       differing line falls in;</li>
     *   <li>{@code {"PARTIAL", <SECTION>, <the rendered prefix text>, <SECTION:line,… >}} - the emitter stopped at a
     *       section it does not render yet, and hands back the FILE AS IT STOOD (v3.3 seat 9, PR #645 commit 5): the
     *       frame, the imports and every section that did render, with that text's own section line starts. The host
     *       compares the prefix with the golden's first N lines and books {@code prefixIdentical} /
     *       {@code prefixDiffering}. The two trailing elements are absent when the stop carried no prefix - a
     *       section method called on its own - so the host must read the LENGTH, never assume it;</li>
     *   <li>{@code {"REFUSED", <reason>}} - the emitter, the property model or the index refused the type by name.</li>
     * </ul>
     * SINCE COMMIT 9 every section of the POJO renders, so an entry is RENDERED unless the emitter, the property
     * model or the index refused the type by name - the PARTIAL shape stays because a section the emitter does
     * not render would still stop it there. Since commit 11 the POJO member is READY, so the host's line is that
     * member's GATE: its own population, {@code differing == 0} against the old generator's own render of the
     * cell, and {@code identical + noGolden == types} (PR #645 round 1 cq SF-1).
     */
    public java.util.Map<String, String[]> pojoShadowRenders() {
        // IN THE ORDER THE PASS BOOKED THEM, not Map.copyOf's - the same MEASURED reason as
        // IRUnitPass.unitShadowRenders (v3.3 seat 9, PR #645 commit 14): the host draws its five no-golden and
        // five divergence samples in this map's iteration order, and Map.copyOf salts that per JVM run, so two
        // runs of ONE head printed two different five-line samples under identical counts. No count and no byte
        // depends on the order; a diffable print does.
        return java.util.Collections.unmodifiableMap(new java.util.LinkedHashMap<>(pojoShadow));
    }

    /**
     * THE MEMBERS THE WIRING DECLARES READY - ONE DECLARATION FOR ALL SIX PASSES (v3.3 seat 9, PR #645 commit 12):
     * it lives on {@link IRTypeUnitWiring}, which the five per-kind derived generators read too, so the
     * all-or-nothing law cannot be true of one pass and false of another because five copies of a literal drifted.
     * This alias keeps the name the commit-11 test asserts on.
     */
    static final Set<IRTypeUnit.Member> READY_MEMBERS = IRTypeUnitWiring.READY_MEMBERS;

    /** The output keys of every file the type unit wrote on this route - empty until the unit is AVAILABLE. */
    private final Set<String> unitWritten = new java.util.LinkedHashSet<>();
    /** Every type NAME the production path asked the unit for, across this pass's models (the host's verdict line). */
    private final Set<String> unitAttempted = new java.util.TreeSet<>();
    /** Every type NAME the production path REFUSED, across this pass's models (the host's verdict line). */
    private final Set<String> unitRefused = new java.util.TreeSet<>();

    /**
     * THE PER-PASS EMITTER MEMO, KEYED BY THE VERSION STAMP (v3.3 seat 10, PR #646 commit 3 - PR #645 round 1
     * cq NIT-1), the POJO pass's half of {@link IRUnitPass}'s. The six emitters are built ONCE PER STAMP rather
     * than once per model, because an emitter is a pure function of this pass's index, its model index, the
     * generator model's pruning set, the type util and the stamp - see {@link IRTypeUnitWiring#membersFor} for the
     * law and for why the shared {@link IRDerivedFacts} is sound and may not be static. It lives on THIS generator,
     * beside the index it was built over.
     */
    private final Map<String, Map<IRTypeUnit.Member, IRTypeUnit.MemberEmitter>> membersByStamp =
            new java.util.HashMap<>();

    /**
     * THE SHADOW'S OWN POJO EMITTER, memoised by the same stamp on this generator (v3.3 seat 10, PR #646 commit 3).
     * It stays a SEPARATE construction from the unit's POJO emitter above - PR #645 round 1 cq SF-1 kept the two
     * apart on purpose, so the shadow measures a second build of the same pure function rather than the very
     * instance the route writes with. The finding asks only that neither be rebuilt PER MODEL.
     */
    private final Map<String, IRDataTypeEmitter> shadowEmitterByStamp = new java.util.HashMap<>();

    /**
     * The data-type emitter for one model's version. Since commit 12 {@link #unitFor} delegates to
     * {@link IRTypeUnitWiring#unitFor}, which constructs its OWN emitter, while {@link #shadowPojos} builds a
     * second through this method - so ONE instance no longer serves both (PR #645 round 1 cq SF-1). What holds is
     * what the file identity needs: the two constructions are the SAME PURE FUNCTION of the same inputs (the
     * index, the version, the doNotPrune set, the type util), and the D11 host's TYPE UNIT VERDICTS line asserts
     * the six passes' verdict sets EQUAL BY NAME - so the file the shadow measures is the file the unit writes.
     *
     * <p>Since v3.3 seat 10, PR #646 commit 3 it is MEMOISED BY THE STAMP on this pass
     * ({@link #shadowEmitterByStamp}) instead of built per model - still a second construction, still never the
     * unit's instance. Package-private since commit 4: {@link IRChoiceObjectGenerator} shadows the CHOICES
     * through THIS emitter over THIS pass's index, so the choice half of the POJO shadow is the same
     * construction as the data types' half and not a seventh one.
     */
    IRDataTypeEmitter emitterFor(String version) {
        return shadowEmitterByStamp.computeIfAbsent(IRTypeUnitWiring.stamp(version),
                stamp -> new IRDataTypeEmitter(index,
                        new IRDataTypeEmitter.Config(stamp, generatorModel.doNotPrune()),
                        typeUtil));
    }

    /**
     * THE PASS'S OWN WORKSPACE-WIDE TYPE INDEX - ONE node per declaration (v3.3 seat 10, PR #646 commit 4). The
     * same package-private seam {@link IRUnitPass#index()} opens on the five derived passes, opened here for
     * {@link IRChoiceObjectGenerator}: the choice POJO shadow runs on THIS pass's index and THIS pass's memoised
     * shadow emitter, because a node from another adapter is not the instance this pass's halves compare.
     */
    IRTypeIndex index() {
        return index;
    }

    /**
     * The type unit for one model's version, with exactly {@link #READY_MEMBERS} declared ready - built by
     * {@link IRTypeUnitWiring}, the ONE construction all six passes take, so the file the D11 SHADOW measures is
     * the file the unit would write. SINCE COMMIT 15 all six members are in the map and
     * {@link IRTypeUnitWiring#AVAILABLE} is true, so {@link IRTypeUnit#available()} is true and
     * {@link IRTypeUnit#verdict} writes every data type whole or refuses it whole BY NAME (PR #645 round 1
     * cq SF-1).
     *
     * <p>Its six EMITTERS come from {@link #membersByStamp}, built once per version stamp on this pass (v3.3 seat
     * 10, PR #646 commit 3); the UNIT is still fresh per call, because its per-node memo and its attempted /
     * refused sets are per-unit state.
     */
    IRTypeUnit unitFor(String version) {
        String stamp = IRTypeUnitWiring.stamp(version);
        return IRTypeUnitWiring.unitFor(membersByStamp.computeIfAbsent(stamp,
                s -> IRTypeUnitWiring.membersFor(index, modelIndex, generatorModel, typeUtil, s)));
    }

