    @Override
    public List<GenerationException> generateClassesAsIR(RModel model, String version,
                                                         Map<String, String> output) {
        List<GenerationException> errors = new ArrayList<>(reconcile(model));
        IRTypeUnit unit = unitFor(version);
        if (unit.available()) {
            // THE UNIT'S OWN PATH, PER MEMBER (v3.3 seat 9, PR #645 commit 12 - the planning review's Q5; written
            // at commit 11 and reached only when the sixth member is declared ready). This pass owns ONE member of
            // the six - the POJO - and writes ONLY its key: the other five belong to the five per-kind derived
            // generators, each reading ITS OWN unit over the same node, and a pass that wrote all six would put a
            // file into the output map its own kind never owned (the "a file has ONE writer" law the D11 asserts).
            //
            // A REFUSAL IS A WHOLE-ELEMENT DECISION: the INHERITED generator's path runs for THAT element, so the
            // old generator's file AND its own errors are produced exactly as on the OFF route. The refusal itself
            // never lands in `errors` - it is this route's reason for taking the other path, not a failure of its
            // own (commit 11 booked it as a generation error and wrote nothing for the type, which would have left
            // a hole where the OFF route writes a file).
            // EVERY element the loop below walked for, in the order it walked them - the input to the population
            // assertion that replaces the old non-data-type split (v3.3 seat 9, PR #645 commit 15)
            List<RRootElement> walked = new ArrayList<>();
            // ONE ELEMENT LOOP FOR SEVEN CALLERS, on IRUnitPass (v3.3 seat 10, PR #646 commit 5 - LAW 69, the
            // commit-3 lift of `inherited` grown to the whole routing law, because the choice route needs the
            // SAME loop over a second population). The two lambdas hand the collaborator THIS generator's
            // createTypeRepresentation and generate, so a refused element's bytes and its errors are the OFF
            // route's exactly as before.
            //
            // THE POPULATION HANDED IN IS THIS GENERATOR'S OWN RE-DERIVATION of the inherited filter - the data
            // types - and NOT `streamObjects(model)`: the assertion below holds the walk against streamObjects's
            // own yield: the two filters are the same filter, and what the assertion witnesses is the LOOP'S WALK
            // against that population - every element walked once, in order, none skipped (lane P1's hole).
            // The choices are IRChoiceObjectGenerator's population on its own pass; a loop that walked them here
            // would put a file into the output map this pass's kind never owned.
            String namespace = model.namespace();
            List<RRootElement> mine = new ArrayList<>();
            for (RRootElement element : model.rootElements()) {
                if (element instanceof RDataType) {
                    mine.add(element);
                }
            }
            errors.addAll(IRUnitPass.routeElements(unit, mine, namespace, version, index,
                    IRTypeUnit.Member.POJO, output, unitWritten, walked,
                    e -> createTypeRepresentation((RDataType) e),
                    (e, r, v) -> generate((RDataType) e, (RJavaPojoInterface) r, v)));
            bookUnitVerdicts(unit);
            assertUnitLoopCoversTheInheritedPopulation(model, walked);
        } else {
            errors.addAll(generateClasses(model, version, output));
        }
        shadowPojos(model, version);
        return errors;
    }

    /**
     * BOOK A UNIT'S VERDICT SETS INTO THIS PASS'S OWN (v3.3 seat 10, PR #646 commit 5). The POJO member is ONE
     * member of the unit and the D11 host reads its {@code attempted} / {@code refused} sets off THIS generator -
     * but since this commit the member is routed by TWO generators, this one over the data types and
     * {@link IRChoiceObjectGenerator} over the choices, each with its own unit instance over the same index and
     * the same memoised emitters. A member's verdict set is the MEMBER'S, not a generator's, so the choice pass
     * books here too and the host's {@code TYPE UNIT VERDICTS} line sees the whole population of the pass.
     */
    void bookUnitVerdicts(IRTypeUnit unit) {
        unitAttempted.addAll(unit.attemptedTypes());
        unitRefused.addAll(unit.refusedTypes());
    }

    /**
     * THE NON-DATA-TYPE SPLIT, WHICH IS EMPTY BY CONSTRUCTION (v3.3 seat 9, PR #645 commit 15 - the switch commit).
     *
     * <p>Until this commit the unit's own path ended in a stated throw, because nobody had established which of the
     * inherited generator's files are the data types' and which are not. The answer is READ from the inherited
     * generator itself: {@code ModelObjectGenerator.streamObjects}
     * ({@code rune-java-generator/src/main/java/com/regnosys/rosetta/generator/java/object/ModelObjectGenerator.java:68-71})
     * is {@code model.rootElements().stream().filter(e -> e instanceof RDataType)} and NOTHING else - the choices
     * are {@code ChoiceObjectGenerator}'s population, on its own pass. So the inherited loop
     * ({@code JavaClassGenerator.generateClasses:58-76}) has NO non-data-type half: there is nothing left for this
     * method to write, and it writes NOTHING.
     *
     * <p>What it does instead is ASSERT that emptiness rather than assume it. It re-derives the inherited
     * generator's OWN population by calling {@code streamObjects} - the same method the inherited loop calls, not a
     * copy of its filter - and holds it EQUAL, element for element and IN ORDER, to the elements the unit's loop
     * above walked (each of which was either written from its verdict or taken through
     * {@link IRUnitPass#inherited}, the ONE declaration of the inherited per-element path since v3.3 seat 10,
     * PR #646 commit 3).
     * A disagreement THROWS BY NAME, and it can only be one of two defects:
     * <ul>
     *   <li>an element {@code streamObjects} yields that the unit's loop never saw - a HOLE: a file the OFF route
     *       writes and this route would not;</li>
     *   <li>an element the loop saw that {@code streamObjects} would not yield - a file with TWO writers.</li>
     * </ul>
     * Neither is visible to a byte gate whose goldens another pass happens to write, which is why both are named
     * here rather than left to a count.
     *
     * @param walked the data types the unit's loop walked, in loop order
     */
    private void assertUnitLoopCoversTheInheritedPopulation(RModel model, List<RRootElement> walked) {
        assertUnitLoopCoversTheInheritedPopulation(model.namespace(), streamObjects(model).toList(), walked);
    }

    /**
     * THE SEAM of the assertion above (package-private): the two populations, HANDED IN. The production overload
     * reads the inherited half off {@code streamObjects}; a test drives THIS one with populations it builds, so the
     * hole arm and the double-writer arm are witnessed without mutating any production state.
     *
     * <p>SINCE v3.3 seat 10, PR #646 commit 5 it is ONE DECLARATION FOR TWO POPULATIONS (LAW 69):
     * {@link IRChoiceObjectGenerator} holds ITS walk against {@code ChoiceObjectGenerator.streamObjects} - the
     * choices of the model, in order - through this same seam. The law is the same law one kind over, so the
     * elements are {@link RRootElement}s and their names come from {@link IRUnitPass#declaredName}.
     *
     * @param modelNamespace the model the two populations belong to - named in every message
     * @param inheritedPopulation what {@code ModelObjectGenerator.streamObjects} yields for that model
     * @param walked the elements the unit's loop walked, in loop order
     */
    static void assertUnitLoopCoversTheInheritedPopulation(String modelNamespace,
            List<? extends RRootElement> inheritedPopulation, List<? extends RRootElement> walked) {
        String where = "IR type unit: the model " + modelNamespace + " - ";
        int common = Math.min(inheritedPopulation.size(), walked.size());
        for (int i = 0; i < common; i++) {
            RRootElement inherited = inheritedPopulation.get(i);
            RRootElement seen = walked.get(i);
            if (inherited != seen) {
                throw new IllegalStateException(where + "the unit's loop and the inherited generator's own"
                        + " population DISAGREE at index " + i + ": streamObjects yields '"
                        + IRUnitPass.declaredName(inherited) + "' where the loop walked '"
                        + IRUnitPass.declaredName(seen) + "'. The POJO pass writes its own kind's declarations and"
                        + " the inherited generator writes nothing beside them, so the two walks are ONE walk or"
                        + " one of them is wrong");
            }
        }
        if (inheritedPopulation.size() > walked.size()) {
            throw new IllegalStateException(where + "the inherited generator would write "
                    + (inheritedPopulation.size() - walked.size()) + " declaration(s) the unit's loop never"
                    + " walked - a HOLE, a file the OFF route writes and this route would not: "
                    + names(inheritedPopulation.subList(walked.size(), inheritedPopulation.size())));
        }
        if (walked.size() > inheritedPopulation.size()) {
            throw new IllegalStateException(where + "the unit's loop walked "
                    + (walked.size() - inheritedPopulation.size()) + " element(s) the inherited generator's own"
                    + " population does not yield - a file with TWO writers: "
                    + names(walked.subList(inheritedPopulation.size(), walked.size())));
        }
    }

    /** The first few names of a population, for a refusal message. */
    private static String names(List<? extends RRootElement> elements) {
        List<String> named = new ArrayList<>();
        for (RRootElement element : elements) {
            if (named.size() == 5) {
                named.add("(+" + (elements.size() - 5) + " more)");
                break;
            }
            named.add(IRUnitPass.declaredName(element));
        }
        return named.toString();
    }

    /**
     * Ask {@link IRDataTypeEmitter} for a SHADOW render of every {@code data} declaration of this model, and book
     * what it answered. The shadow runs AFTER the pass's own generation and writes into no output map - it is a
     * measurement, not an emission, and a throw of any kind is BOOKED rather than raised, so a shadow can never
     * break a generation that the route would otherwise complete.
     *
     * <p>The PRUNING half of the emitter's config is the generator model's OWN {@code doNotPrune} set, read
     * through the seam {@code GeneratorModel.doNotPrune()} (v3.3 seat 9, PR #645 commit 9): section 12's
     * {@code prune()} and {@code hasData()} arms branch on it per {@code (type, attribute)} pair, exactly as
     * {@code ModelObjectGenerator:1315-1316} and {@code :1359-1360} do, and the D11 host has already fed this
     * generator model the cell's own entries from {@code rosetta-config.yml} - so nothing is re-read from the
     * yml and nothing is guessed. Commit 4's placeholder boolean, which no section read, is gone. The version is
     * the host's, per model, as every other emitter takes it.
     */
    private void shadowPojos(RModel model, String version) {
        IRDataTypeEmitter emitter = emitterFor(version);   // commit 11: the SAME construction the unit takes
        String namespace = model.namespace();
        for (RRootElement element : model.rootElements()) {
            if (!(element instanceof RDataType dataType)) {
                continue;
            }
            String key;
            IRTypeNode node;
            try {
                node = index.node(namespace, dataType);
                key = IRDataTypeEmitter.outputKey(node);
            } catch (RuntimeException e) {
                // the node or its key could not even be formed: book it under the DECLARATION's qualified name, so
                // the type is still counted and named rather than dropped from the shadow's population
                pojoShadow.put(namespace + "." + dataType.name() + " (no output key)",
                        new String[] {"REFUSED", IRUnitPass.reason(e)});
                continue;
            }
            try {
                IRDataTypeEmitter.Rendered rendered = emitter.renderWithSections(node);
                pojoShadow.put(key, new String[] {"RENDERED", rendered.text(),
                        renderSectionLineStarts(rendered.sectionLineStarts())});
            } catch (IRDataTypeEmitter.NotYetRendered partial) {
                // v3.3 seat 9 (PR #645 commit 5): a partial render hands back the prefix it DID produce, so the host
                // can hold it against the golden's first N lines. A stop with no prefix books the two-element form.
                pojoShadow.put(key, partial.prefix()
                        .map(prefix -> new String[] {"PARTIAL", partial.section().name(), prefix.text(),
                                renderSectionLineStarts(prefix.sectionLineStarts())})
                        .orElseGet(() -> new String[] {"PARTIAL", partial.section().name()}));
            } catch (RuntimeException e) {
                pojoShadow.put(key, new String[] {"REFUSED", IRUnitPass.reason(e)});
            }
        }
    }

    /** {@code SECTION:line,SECTION:line,…} - the host parses it to name the section a differing line falls in. */
    /**
     * <p>Package-private since v3.3 seat 10, PR #646 commit 4: {@link IRChoiceObjectGenerator} books the
     * SAME three entry shapes for the choices, and ONE declaration of this encoding serves both maps
     * (LAW 69) - two spellings would let the host's reader agree with one half and not the other.
     */
    static String renderSectionLineStarts(java.util.Map<String, Integer> lineStarts) {
        StringBuilder sb = new StringBuilder();
        for (java.util.Map.Entry<String, Integer> entry : lineStarts.entrySet()) {
            if (sb.length() > 0) {
                sb.append(',');
            }
            sb.append(entry.getKey()).append(':').append(entry.getValue());
        }
        return sb.toString();
    }

    /**
     * Build the STRUCT IR for each data type in the model - and the TYPE_ALIAS IR for each {@code typeAlias} - and
     * assert EVERY fact each carries against the source, each population through its own reconciler. Then (v3.3 seat 8,
     * PR #644) read the model's PROPERTY SURFACE and DERIVED FACTS for every validated element, and the MODEL node
     * itself, each through its own reconciler and its own counters.
     */
    List<GenerationException> reconcile(RModel model) {   // package-private: the throw witness calls the reconcile alone
        List<GenerationException> errors = new ArrayList<>();
        String namespace = model.namespace();
        for (var element : model.rootElements()) {
            if (element instanceof RDataType dataType) {
                reconciler.attempt();   // counted BEFORE the adapter: a throw below is a mismatch, never a silent drop
                try {
                    // the INDEX's instance (PR #644 round 1, cq SF-1): the declaration facts, the property surface and the
                    // derived facts are now asserted on ONE node - the one the property law's walks read - not on two equal ones
                    IRTypeNode ir = index.node(namespace, dataType);
                    for (String mismatch : reconciler.reconcileData(namespace, dataType, ir)) {
                        errors.add(new GenerationException(mismatch, null, dataType));
                    }
                } catch (RuntimeException e) {
                    reconciler.threw();
                    errors.add(new GenerationException(
                            "AST->IR adapter failed for data " + dataType.name(),
                            null, dataType, e));
                }
            } else if (element instanceof RTypeAlias alias) {
                aliasReconciler.attempt();   // its own population, counted BEFORE the adapter
                try {
                    // the alias reconciler's adapter IS the data reconciler's (shared at construction)
                    IRTypeNode ir = aliasReconciler.adapter().adaptTypeAlias(namespace, alias);
                    for (String mismatch : aliasReconciler.reconcileTypeAlias(namespace, alias, ir)) {
                        errors.add(new GenerationException(mismatch, null, alias));
                    }
                } catch (RuntimeException e) {
                    aliasReconciler.threw();
                    errors.add(new GenerationException(
                            "AST->IR adapter failed for typeAlias " + alias.name(),
                            null, alias, e));
                }
            }
        }
        errors.addAll(reconcileProperties(model, namespace));
        errors.addAll(reconcileModelNode(model));
        return errors;
    }

    /**
     * THE PROPERTY AND DERIVED READS (v3.3 seat 8, PR #644). One population - the cell's VALIDATED ELEMENTS, its
     * {@code data} types and its {@code choice}s together - read twice: once as the POJO property surface the type
     * emitter will write from, once as the input facts its per-type DERIVED files stand on. Both are booked BEFORE
     * either half runs, so an element whose property model REFUSES (the two named refusals of {@link IRPropertyModel})
     * or throws is a mismatch on BOTH lines rather than a declaration missing from a population. The nodes the reads
     * used are kept for the once-per-cell wrapper reconcile, which needs the whole cell before it can compare a set.
     */
    private List<GenerationException> reconcileProperties(RModel model, String namespace) {
        List<GenerationException> errors = new ArrayList<>();
        for (RRootElement element : model.rootElements()) {
            if (!(element instanceof RDataType) && !(element instanceof RChoice)) {
                continue;
            }
            propertyReconciler.attempt();
            derivedReconciler.attempt();   // ONE population: the derived read is owed for this element either way
            IRTypeNode node;
            IRPropertyModel properties;
            try {
                if (element instanceof RDataType dataType) {
                    node = index.node(namespace, dataType);
                    properties = IRPropertyModel.of(node, index);
                    for (String mismatch : propertyReconciler.reconcile(namespace, dataType, properties)) {
                        errors.add(new GenerationException(mismatch, null, dataType));
                    }
                } else {
                    RChoice choice = (RChoice) element;
                    node = index.node(namespace, choice);
                    properties = IRPropertyModel.of(node, index);
                    for (String mismatch : propertyReconciler.reconcile(namespace, choice, properties)) {
                        errors.add(new GenerationException(mismatch, null, choice));
                    }
                }
            } catch (RuntimeException e) {
                propertyReconciler.threw();
                // the derived facts stand ON the property model: no model, no read - and a read that never happened is
                // a mismatch here, never a quiet hole in the derived line's population
                derivedReconciler.threw();
                errors.add(new GenerationException(
                        "AST->IR property model failed for " + elementName(element), null, element, e));
                continue;
            }
            emittedTypeNodes.add(node);
            try {
                for (String mismatch : derivedReconciler.reconcile(namespace, element, node, properties, index)) {
                    errors.add(new GenerationException(mismatch, null, element));
                }
            } catch (RuntimeException e) {
                derivedReconciler.threw();
                errors.add(new GenerationException(
                        "IR derived-facts reconcile failed for " + elementName(element), null, element, e));
            }
        }
        return errors;
    }

    /** The MODEL node of this model, adapted through the pass's own adapter and asserted against its source. */
    private List<GenerationException> reconcileModelNode(RModel model) {
        List<GenerationException> errors = new ArrayList<>();
        modelReconciler.attempt();   // counted BEFORE the adapter, as every population here is
        try {
            IRModelNode node = modelIndex.node(model);   // the index's instance: adapted once, the same node every half reads
            emittedModelNodes.add(node);
            for (String mismatch : modelReconciler.reconcile(model, node)) {
                errors.add(new GenerationException(mismatch, null, model));
            }
        } catch (RuntimeException e) {
            modelReconciler.threw();
            errors.add(new GenerationException(
                    "AST->IR adapter failed for model " + model.namespace(), null, model, e));
        }
        return errors;
    }

    /**
     * The WRAPPER spec set is a fact of the whole CELL - a spec is claimed by the FIRST of four sources to reach its
     * dedup key, and two of those sources are function signatures and {@code with-meta} expressions, which no single
     * declaration carries. So the reconcile waits until the pass is over and runs ONCE, on the host's first read;
     * a throw is a mismatch and its message is the one the host prints.
     */
    private void reconcileWrappersOnce() {
        if (wrapperReconcileMismatches != null) {
            return;
        }
        try {
            wrapperReconcileMismatches = List.copyOf(
                    wrapperReconciler.reconcile(List.copyOf(emittedModelNodes), List.copyOf(emittedTypeNodes)));
        } catch (RuntimeException e) {
            wrapperReconciler.threw();
            wrapperReconcileMismatches = List.of("IR/AST reconciliation failed for WRAPPERS: the spec set could not be"
                    + " derived from the IR - " + e.getClass().getSimpleName() + ": " + e.getMessage());
        }
    }

    /** The declared name of a validated element, for a refusal message that names what it refused. */
    private static String elementName(RRootElement element) {
        return element instanceof RDataType dataType ? dataType.name() : ((RChoice) element).name();
    }
